"""Write a recorded airline call as the browser client's test fixture.

The call is recorded from the real tools: this script plays a scripted caller against ``AirlineTools`` on a fixed clock
and writes each tool call, with its arguments and its whole output, as the ``live-event`` messages that the server
relays, grouped into steps. The client's tests feed them through the same code as a live call's, so they check what the
tools really return. Run it after you change a tool, the timetable or the sample accounts:

    uv run python scripts/export_airline_demo.py          # write clients/pipecat/tests/airline-recorded-call.ts
    uv run python scripts/export_airline_demo.py --check  # exit 1 when the file is out of date
"""

from __future__ import annotations

import argparse
import asyncio
import json
import sys
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from nemotron_voice_agent.pipecat.examples.frontend_backend_live.delegation_core.backend.tools.airline.schemas import (
    AIRLINE_TOOLS,
)
from nemotron_voice_agent.pipecat.examples.frontend_backend_live.delegation_core.backend.tools.airline.tools import (
    AirlineTools,
)
from nemotron_voice_agent.pipecat.examples.frontend_backend_live.prompts import load_prompts

TARGET = Path(__file__).resolve().parents[1] / "clients" / "pipecat" / "tests" / "airline-recorded-call.ts"
# The recording's "today": a Wednesday, the same day the tool tests use, so it comes out the same on any day.
NOW = datetime(2026, 11, 4, 12, 0, tzinfo=UTC)
TOMORROW = "2026-11-05"
MODEL = "nvidia/nemotron-3.5-super-vl-120b-a12b"
CONVERSATION = "conv_5e1b0d7c9a24"

HEADER = """// SPDX-FileCopyrightText: Copyright (c) 2024-2026, NVIDIA CORPORATION & AFFILIATES. All rights reserved.
// SPDX-License-Identifier: Apache-2.0

// A call recorded from the real airline tools on a fixed day, as the `live-event` messages that the server relays: the
// client's test fixture. Generated by scripts/export_airline_demo.py; do not edit it by hand. A unit test fails when it
// is out of date. Everything in it is made up: the airline, the traveler, the flights and the fares.

export interface DemoTurn {
  role: "user" | "assistant";
  text: string;
}

/** One step of the recorded call: what is said, the events the server would relay, and what the agent is doing. */
export interface DemoStep {
  id: string;
  /** A short name for the step. */
  title: string;
  turns: DemoTurn[];
  /** The `live-event` messages of this step, in order. */
  events: Record<string, unknown>[];
  agent: string;
  /** The gentle activity phrase shown while the agent works, or null. */
  activity: string | null;
}

"""


class Recorder:
    """The relayed events of the whole call, numbered and timed as the server numbers and times them."""

    def __init__(self) -> None:
        """Start at the first event, with the size of the backend's prompt that the events show."""
        self.seq, self.clock, self.responses = 0, 0.1, 0
        self.instructions = len(
            f"{load_prompts().text('Backend', 'airline')}\n\n{load_prompts().text('Channel', 'airline')}"
        )

    def message(self, direction: str, kind: str, stream: str | None, event: dict[str, Any]) -> dict[str, Any]:
        """Return one relayed event, numbered and timed as the server numbers and times them."""
        self.seq += 1
        self.clock += 0.35
        return {
            "type": "live-event",
            "v": 1,
            "seq": self.seq,
            "t": round(self.clock, 3),
            "direction": direction,
            "kind": kind,
            "stream": stream,
            "delegation": f"item_{self.responses:03d}" if stream else None,
            "event": event,
        }

    def conversation(self) -> dict[str, Any]:
        """Return the event of the conversation that the bot opens first."""
        return self.message("out", "conversations.create", None, {"id": CONVERSATION, "metadata": {}})

    def response(self) -> dict[str, Any]:
        """Return the response object that a stream's lifecycle events carry."""
        return {
            "id": f"resp_{self.responses:02d}b6e2c41d93",
            "object": "response",
            "status": "queued",
            "model": MODEL,
            "instructions": f"<{self.instructions:,} chars>",
            "output": [],
        }

    async def turn(self, desk: AirlineTools, said: str, calls: list[tuple[str, dict[str, Any]]], answer):
        """Return the events of one request, and the answer: (events before the tool calls finish, events after, text).

        The calls run on ``desk`` first; ``answer`` says the outputs in words. The first call's start comes before, so a
        step can show the agent at work; everything else comes after.
        """
        self.responses += 1
        stream = f"r{self.responses}"
        outputs = [
            await desk.execute(f"demo_{self.responses}_{i}", name, json.dumps(args))
            for i, (name, args) in enumerate(calls)
        ]
        text = answer([json.loads(output) for output in outputs])
        before = [
            self.message(
                "out",
                "responses.create",
                stream,
                {
                    "input": [{"role": "user", "content": [{"type": "input_text", "text": said}]}],
                    "conversation": CONVERSATION,
                    "metadata": {"live_delegation_id": f"item_{self.responses:03d}"},
                    "instructions": f"<{self.instructions:,} chars>",
                    "tools": [tool["name"] for tool in AIRLINE_TOOLS],
                    "stream": True,
                },
            ),
            self.message("in", "response.created", stream, {"type": "response.created", "response": self.response()}),
            self.message(
                "in",
                "response.in_progress",
                stream,
                {"type": "response.in_progress", "response": {**self.response(), "status": "in_progress"}},
            ),
        ]
        after: list[dict[str, Any]] = []
        items: list[dict[str, Any]] = []
        for index, ((name, arguments), output) in enumerate(zip(calls, outputs, strict=True)):
            item_id = f"mcp_{self.responses:02d}{index:02d}a7c5e19f"
            call = {"id": item_id, "type": "mcp_call", "server_label": "airline", "name": name, "error": None}
            arguments_text = json.dumps(arguments, separators=(",", ":"))
            added = self.message(
                "in",
                "response.output_item.added",
                stream,
                {
                    "type": "response.output_item.added",
                    "output_index": index,
                    "item": {**call, "status": "in_progress", "arguments": arguments_text, "output": None},
                },
            )
            rest = [
                self.message(
                    "in",
                    f"response.mcp_call.{phase}",
                    stream,
                    {"type": f"response.mcp_call.{phase}", "item_id": item_id, "output_index": index},
                )
                for phase in ("in_progress", "completed")
            ]
            rest.append(
                self.message(
                    "in",
                    "response.output_item.done",
                    stream,
                    {
                        "type": "response.output_item.done",
                        "output_index": index,
                        "item": {**call, "status": "completed", "arguments": arguments_text, "output": output},
                    },
                )
            )
            items.append(
                {
                    **call,
                    "status": "completed",
                    "arguments": f"<{len(arguments_text)} chars>",
                    "output": f"<{len(output):,} chars>",
                }
            )
            (before if index == 0 else after).append(added)
            after.extend(rest)
        after.append(
            self.message(
                "in",
                "response.output_text.done",
                stream,
                {
                    "type": "response.output_text.done",
                    "item_id": f"msg_{self.responses:02d}d3a91e5c04",
                    "output_index": len(calls),
                    "text": text,
                },
            )
        )
        done = {**self.response(), "status": "completed", "output": items}
        done["usage"] = {"input_tokens": 3200 + 900 * self.responses, "output_tokens": 60 + 4 * len(text.split())}
        after.append(self.message("in", "response.completed", stream, {"type": "response.completed", "response": done}))
        return before, after, text


def number(count: int) -> str:
    """Return a small count in words, capitalised: 4 is "Four"."""
    return {1: "One", 2: "Two", 3: "Three", 4: "Four", 5: "Five"}.get(count, str(count))


async def record() -> list[dict[str, Any]]:
    """Play the scripted caller and return the recorded steps."""
    desk = AirlineTools(clock=lambda: NOW, seed=7)
    recorder = Recorder()
    steps: list[dict[str, Any]] = []

    def step(step_id: str, title: str, turns: list[tuple[str, str]], events: list, agent: str, activity: str | None):
        turns_data = [{"role": role, "text": text} for role, text in turns]
        steps.append(
            {"id": step_id, "title": title, "turns": turns_data, "events": events, "agent": agent, "activity": activity}
        )

    greeting = "Hi, this is Ava at the Demo Air travel desk. How can I help you today?"
    step("connect", "Call connects", [("assistant", greeting)], [recorder.conversation()], "listening", None)

    # A search: the agent works first, then the options appear.
    search = {"origin": "Boston", "destination": "Denver", "date": TOMORROW}

    def found(outputs: list[dict[str, Any]]) -> str:
        result = outputs[0]
        one, two = result["flights"][0], result["flights"][1]
        return (
            f"{number(result['count'])} flights match. One at {one['depart_spoken']} for {one['price_spoken']}, and "
            f"one at {two['depart_spoken']} for {two['price_spoken']}. The rest are on your screen. Demo Air is a "
            "made-up airline, so nothing here is real or charged. Which would you like?"
        )

    ask = "I need a flight from Boston to Denver tomorrow."
    before, after, said = await recorder.turn(desk, ask, [("flights_search", search)], found)
    step("ask", "Ask for flights", [("user", ask)], before, "thinking", "Checking flights…")
    step("results", "Options appear", [("assistant", said)], after, "speaking", None)

    # Picking one needs an account: the tool asks for a sign-in, and the screen offers the sample accounts.
    pick = "Book the first one."
    asked = "I'll need you to sign in first. Say a user ID, or I can create a demo account in your name."
    before, after, _ = await recorder.turn(desk, pick, [("new_booking", {"flight": "1"})], lambda outputs: asked)
    step("pick", "Pick an option", [("user", pick), ("assistant", asked)], [*before, *after], "speaking", None)

    # Signing in shows the trips; the booking is read back and waits for a yes.
    sign = "My user ID is jane doe zero zero one."
    calls = [("sign_in", {"user_id": "jane_doe_001"}), ("new_booking", {"flight": "1"})]
    before, after, said = await recorder.turn(desk, sign, calls, lambda outputs: outputs[-1]["confirmation_summary"])
    step("sign-in", "Sign in", [("user", sign), ("assistant", said)], [*before, *after], "speaking", None)

    yes = "Yes, go ahead."
    confirmed = [("new_booking", {"flight": "1", "confirmed": True})]
    before, after, said = await recorder.turn(desk, yes, confirmed, lambda outputs: outputs[0]["summary"])
    step("book", "Confirm and book", [("user", yes), ("assistant", said)], [*before, *after], "speaking", None)

    # A flight check: the status, then its on-time record.
    check = "Is my other flight tomorrow on time?"

    def status(outputs: list[dict[str, Any]]) -> str:
        return f"{outputs[0]['summary']} It runs on time {outputs[1]['on_time_pct']} percent of the time."

    flight = {"flight_number": "DA 213"}
    before, after, said = await recorder.turn(
        desk, check, [("get_flight_status", flight), ("get_ontime_trend", flight)], status
    )
    step("status", "Check a flight", [("user", check), ("assistant", said)], [*before, *after], "speaking", None)

    # A city the airline does not serve.
    boise = "Can I fly from Boise to Denver?"
    scope = {"origin": "Boise", "destination": "Denver", "date": TOMORROW}
    before, after, said = await recorder.turn(
        desk, boise, [("flights_search", scope)], lambda outputs: f"{outputs[0]['message']} {outputs[0]['question']}"
    )
    step(
        "scope",
        "A city it does not serve",
        [("user", boise), ("assistant", said)],
        [*before, *after],
        "listening",
        None,
    )
    return steps


def render() -> str:
    """Return the file's text: the header and the recorded steps."""
    steps = asyncio.run(record())
    body = json.dumps(steps, indent=2, ensure_ascii=False)
    return f"{HEADER}export const RECORDED_CALL: readonly DemoStep[] = {body};\n"


def main() -> int:
    """Write the file, or with ``--check`` say whether it is current."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="do not write; exit 1 when the file is out of date")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            print(f"{TARGET} is out of date: run scripts/export_airline_demo.py", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
